void gfx_target(uint32_t *px, int stride) { tgt = px; tstride = stride; }

static inline uint32_t mix(uint32_t d, uint32_t s, int a)
{
    uint32_t r = ((s & 0xFF) * a + (d & 0xFF) * (255 - a)) / 255;
    uint32_t g = (((s >> 8) & 0xFF) * a + ((d >> 8) & 0xFF) * (255 - a)) / 255;
    uint32_t b = (((s >> 16) & 0xFF) * a + ((d >> 16) & 0xFF) * (255 - a)) / 255;
    return 0xFF000000u | (b << 16) | (g << 8) | r;
}

static inline void plot(int x, int y, uint32_t c, int a)
{
    if ((unsigned)x >= SCR_W || (unsigned)y >= SCR_H) return;
    uint32_t *p = &tgt[y * tstride + x];
    *p = (a >= 255) ? c : mix(*p, c, a);
}

void gfx_rect(int x, int y, int w, int h, uint32_t c)
{
    if (x < 0) { w += x; x = 0; }
    if (y < 0) { h += y; y = 0; }
    if (x + w > SCR_W) w = SCR_W - x;
    if (y + h > SCR_H) h = SCR_H - y;
    if (w <= 0 || h <= 0) return;
    for (int j = 0; j < h; j++) {
        uint32_t *p = &tgt[(y + j) * tstride + x];
        for (int i = 0; i < w; i++) p[i] = c;
    }
}

void gfx_fill(uint32_t c) { gfx_rect(0, 0, SCR_W, SCR_H, c); }

void gfx_rrect(int x, int y, int w, int h, int r, uint32_t c)
{
    if (w <= 0 || h <= 0) return;
    if (r * 2 > w) r = w / 2;
    if (r * 2 > h) r = h / 2;
    if (r <= 0) { gfx_rect(x, y, w, h, c); return; }

    gfx_rect(x + r, y, w - 2 * r, h, c);
    gfx_rect(x, y + r, r, h - 2 * r, c);
    gfx_rect(x + w - r, y + r, r, h - 2 * r, c);

    for (int j = 0; j < r; j++) {
        for (int i = 0; i < r; i++) {
            float dx = (float)r - (i + 0.5f);
            float dy = (float)r - (j + 0.5f);
            float cov = (float)r - sqrtf(dx * dx + dy * dy) + 0.5f;
            if (cov <= 0.0f) continue;
            if (cov > 1.0f) cov = 1.0f;
            int a = (int)(cov * 255.0f);
            plot(x + i,         y + j,         c, a);
            plot(x + w - 1 - i, y + j,         c, a);
            plot(x + i,         y + h - 1 - j, c, a);
            plot(x + w - 1 - i, y + h - 1 - j, c, a);
        }
    }
}

int gfx_text_w(const char *s, int scale) { return (int)strlen(s) * 6 * scale; }

int gfx_text(int x, int y, const char *s, uint32_t c, int scale)
{
    int x0 = x;
    for (; *s; s++) {
        unsigned ch = (unsigned char)*s;
        if (ch < 32 || ch > 126) ch = '?';
        const uint8_t *g = font[ch - 32];
        for (int col = 0; col < 5; col++) {
            uint8_t bits = g[col];
            if (!bits) continue;
            for (int row = 0; row < 8; row++)
                if (bits & (1u << row))
                    gfx_rect(x + col * scale, y + row * scale, scale, scale, c);
        }
        x += 6 * scale;
    }
    return x - x0;
}

void gfx_fit(char *out, size_t n, const char *s, int maxw, int scale)
{
    int maxc = maxw / (6 * scale);
    int len = (int)strlen(s);
    if (maxc < 3) maxc = 3;
    if (len <= maxc) { snprintf(out, n, "%s", s); return; }
    int k = maxc - 2;
    if (k > (int)n - 4) k = (int)n - 4;
    if (k < 0) k = 0;
    memcpy(out, s, (size_t)k);
    while (k > 0 && out[k - 1] == ' ') k--;
    out[k] = 0;
    strcat(out, "..");
}
